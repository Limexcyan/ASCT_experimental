% M10 example: capture already finished M4 STEP9 and STEP10 without rerunning.
% Run from a checkout containing multiverse/asct_m5_digest.m and M10 sources.
% This is a PARTIAL lineage snapshot (ROI -> CONN), not proof that ICA passed.
root='/mnt/devv/Exp/LG/wprawki/flanker';
original='flanker_step0_wide_narrow_m4_v2__mv_0001';
roiRun='flanker_step0_wide_narrow_m4_v2_step9__mv_0001';
connRun='flanker_step0_wide_narrow_m4_v2_step10__mv_0001';
setup=fullfile(root,original,'multiverse_setup.mat');
assert(isfile(setup),'Missing original M4 setup');
s=load(setup,'runsetup');
assert(isfield(s,'runsetup'),'Missing original runsetup');
p=s.runsetup;

% CODE REVISION is historical metadata supplied by the experimenter.
% Do not treat it as proof of the actual fossil checkout revision.
spec.experimentId='flanker_m4_v2_wide_recovered_mv_0001';
spec.codeRevision='46041b6b';
spec.parameters=struct('setupSHA256',asct_m5_digest(setup), ...
    'bandHz',[2 48],'nROIs',numel(p.loc.ROI), ...
    'recoveryStatus','historical-manual-not-registered', ...
    'lineageScope','ROI-to-CONN-only');

spec.artifacts(1)=struct('id','wide_roi','variantId','mv_0001', ...
    'stage','ROI','root',fullfile(root,roiRun), ...
    'patterns',{{'7_SOURCEACT/DC1/lc/*_sigroi_lc.mat', ...
                 '7_SOURCEACT/DC2/lc/*_sigroi_lc.mat'}}, ...
    'upstream',{{}},'settings',struct('nROIs',numel(p.loc.ROI), ...
        'leakageCorrected',true),'expectedCount',8);
spec.artifacts(2)=struct('id','wide_conn','variantId','mv_0001', ...
    'stage','CONN','root',fullfile(root,connRun), ...
    'patterns',{{'8_CONN/FPN_300_600/lc/DC1/*_mltin.mat', ...
                 '8_CONN/FPN_300_600/lc/DC1/*_mltout.mat', ...
                 '8_CONN/FPN_300_600/lc/DC2/*_mltin.mat', ...
                 '8_CONN/FPN_300_600/lc/DC2/*_mltout.mat', ...
                 '8_CONN/FPN_300_600/mv.mat', ...
                 '8_CONN/FPN_300_600/labels.txt'}}, ...
    'upstream',{{'wide_roi'}},'settings',p.con, ...
    'expectedCount',18);

% Snapshot goes OUTSIDE the source run folders. Use a new folder per capture.
out=fullfile(getenv('HOME'),'m10_snapshots', ...
    ['m4_wide_roi_conn_' datestr(now,'yyyymmdd_HHMMSS')]);
manifest=asct_m10_snapshot(spec,out);
report=asct_m10_verify(fullfile(out,'snapshot.mat'));
assert(report.ok,'M10 snapshot failed its own SHA-256 verification');
fprintf('M10 snapshot: %s\n',out);
fprintf('Snapshot digest: %s\n',manifest.snapshotDigest);
fprintf('Verified files: %d\n',numel(report.files));
