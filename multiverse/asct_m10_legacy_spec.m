function spec=asct_m10_legacy_spec(experimentId,codeRevision,parameters,stages)
%ASCT_M10_LEGACY_SPEC Build an explicit read-only historical import specification.
% Requires id, variantId, stage, root, patterns, upstream, settings,
% expectedCount for every stage. Never imports into the M5 reuse registry.
assert(isstruct(stages) && ~isempty(stages) && ...
    all(isfield(stages,{'id','variantId','stage','root','patterns', ...
    'upstream','settings','expectedCount'})), ...
    'ASCT:M10:BadLegacySpec','Explicit coverage is required for each stage');
assert(isstruct(parameters) && isscalar(parameters), ...
    'ASCT:M10:BadLegacySpec','Parameters must be a scalar struct');
ids=cellstr(string({stages.id}));
assert(numel(unique(ids))==numel(ids) && ...
    all(~cellfun(@isempty,ids)), 'ASCT:M10:BadLegacySpec','Duplicate/empty IDs');
for k=1:numel(stages)
    a=stages(k); n=a.expectedCount;
    assert(isnumeric(n) && isscalar(n) && isfinite(n) && n>=1 && n==fix(n), ...
        'ASCT:M10:BadLegacySpec','Each stage needs a positive expectedCount');
    assert(isstruct(a.settings) && isscalar(a.settings), ...
        'ASCT:M10:BadLegacySpec','Stage settings must be a scalar struct');
    assert(isfolder(char(string(a.root))), ...
        'ASCT:M10:MissingRoot','Source directory missing');
    up=cellstr(string(a.upstream));
    assert(numel(unique(up))==numel(up) && all(ismember(up,ids(1:k-1))), ...
        'ASCT:M10:BadDependency','Dependencies must reference earlier stages');
end
spec=struct('experimentId',char(string(experimentId)), ...
    'codeRevision',char(string(codeRevision)), ...
    'parameters',parameters,'artifacts',stages);
end
