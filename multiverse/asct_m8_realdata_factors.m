function [factors,requiredROIs] = asct_m8_realdata_factors(setup,roiCounts)
%ASCT_M8_REALDATA_FACTORS Validated STEP10 grid for existing real-data ASCT.
% A SETUP WITH 12 REAL RECONSTRUCTED ROI SIGNALS IS REQUIRED for 1-12.
% Merely selecting con.chanSel='1-12' never creates additional ROIs.
if nargin<2 || isempty(roiCounts),roiCounts=[5 8 12];end
assert(isstruct(setup) && isfield(setup,'loc') && ...
    isfield(setup.loc,'ROI') && isfield(setup,'con'), ...
    'ASCT:M8:Setup','Expected base setup with loc.ROI and con');
assert(isnumeric(roiCounts) && isvector(roiCounts) && ...
    ~isempty(roiCounts) && all(roiCounts>=5) && all(roiCounts<=12) && ...
    all(roiCounts==fix(roiCounts)), ...
    'ASCT:M8:ROI','ROI counts must be integers 5..12');
roiCounts=unique(roiCounts(:)','stable');
requiredROIs=max(roiCounts);
assert(numel(setup.loc.ROI)>=requiredROIs, ...
    'ASCT:M8:InsufficientROIs', ...
    'Base setup defines %d ROIs; need %d REAL ROIs for this grid', ...
    numel(setup.loc.ROI),requiredROIs);
assert(isfield(setup.con,'mvarOrd') && setup.con.mvarOrd>=1 && ...
    setup.con.mvarOrd==fix(setup.con.mvarOrd), ...
    'ASCT:M8:FixedOrder','Base con.mvarOrd must be a positive integer');
sel=cell(1,numel(roiCounts));
for j=1:numel(roiCounts),sel{j}=sprintf('1-%d',roiCounts(j));end
factors=struct('chanSel',{sel},'orderSelection',{{'fixed','aic'}}, ...
    'varNorm',[0 1],'removeERP',[false true]);
end
