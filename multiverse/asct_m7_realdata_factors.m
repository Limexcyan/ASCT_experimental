function [factors,includeFcn,expectedRuns] = asct_m7_realdata_factors(baseLoc,lambdas,depthWeights)
%ASCT_M7_REALDATA_FACTORS Factor specification for existing ASCT STEP8.
% Use with mv.factors.loc, mv.includeFcn, mv.maxRuns and
% asct_multiverse_plan(setup,mv); does NOT launch a real-data analysis.
% cov mode has no operative lambda, so retain only baseline lambda.
assert(isstruct(baseLoc) && isfield(baseLoc,'lambda') && ...
    isscalar(baseLoc.lambda) && isfinite(baseLoc.lambda) && baseLoc.lambda>0, ...
    'ASCT:M7:Baseline','Baseline loc.lambda must be positive');
assert(isnumeric(lambdas) && isvector(lambdas) && ~isempty(lambdas) && ...
    all(isfinite(lambdas)) && all(lambdas>0), ...
    'ASCT:M7:Lambda','Need positive lambda candidates');
assert(isnumeric(depthWeights) && isvector(depthWeights) && ~isempty(depthWeights) && ...
    all(isfinite(depthWeights)) && all(depthWeights>=0) && all(depthWeights<=1), ...
    'ASCT:M7:Depth','Depth weights must be in [0,1]');
lambdas=unique([baseLoc.lambda lambdas(:)'],'stable');
depthWeights=unique(depthWeights(:)','stable');
factors=struct('norm',{{'lambda','cov'}},'lambda',lambdas, ...
    'depthWeight',depthWeights);
baseLambda=baseLoc.lambda;
includeFcn=@(changes) strcmp(char(changes.loc.norm),'lambda') || ...
    isequal(changes.loc.lambda,baseLambda);
expectedRuns=(numel(lambdas)+1)*numel(depthWeights);
end
