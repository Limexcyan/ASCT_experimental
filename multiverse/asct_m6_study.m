function [T,summary] = asct_m6_study(outputDir,opts)
%ASCT_M6_STUDY Paired oracle vs geometric-inverse single-case benchmark.
% Each row is an INDEPENDENT synthetic realization. No FieldTrip/multar.
% The scenario set spans 3..10 sources, spacing, density, strength, lag, SNR.
if nargin<1 || isempty(outputDir)
    outputDir=fullfile(pwd,'m6_results');
end
if nargin<2,opts=struct();end
assert(~isfolder(outputDir),'ASCT:Study:OutputExists', ...
    'Output directory already exists: %s',outputDir);
if ~isfield(opts,'nReplicates'),opts.nReplicates=5;end
if ~isfield(opts,'nBootstrap'),opts.nBootstrap=500;end
if ~isfield(opts,'seed'),opts.seed=20261119;end
if ~isfield(opts,'simulation')
    opts.simulation=struct('fs',128,'nSamples',384,'nTrials',12,'nSensors',24);
end
if ~isfield(opts,'inverse')
    opts.inverse=struct('norm','lambda','lambda',0.05,'depthWeight',0.5);
end
if ~isfield(opts,'mvar')
    opts.mvar=struct('orderMode','fixed','fixedOrder',2,'maxMvarOrder',6, ...
        'varNorm',false,'removeERP',false);
end
if ~isfield(opts,'scenarios')
    opts.scenarios=[ ...
        struct('nSources',3,'distanceCm',1.5,'nInteractions',1,'strength',0.2,'lag',1,'snrDb',0); ...
        struct('nSources',4,'distanceCm',6.0,'nInteractions',2,'strength',0.4,'lag',2,'snrDb',15); ...
        struct('nSources',6,'distanceCm',1.5,'nInteractions',4,'strength',0.4,'lag',1,'snrDb',15); ...
        struct('nSources',8,'distanceCm',6.0,'nInteractions',6,'strength',0.2,'lag',2,'snrDb',0); ...
        struct('nSources',10,'distanceCm',1.5,'nInteractions',9,'strength',0.4,'lag',2,'snrDb',15); ...
        struct('nSources',10,'distanceCm',6.0,'nInteractions',9,'strength',0.2,'lag',1,'snrDb',0)];
end
assert(opts.nReplicates>=2 && opts.nReplicates==fix(opts.nReplicates) && ...
    opts.nBootstrap>=100 && opts.nBootstrap==fix(opts.nBootstrap), ...
    'ASCT:M6:Runs','Need >=2 independent replicates and >=100 bootstraps');
nSc=numel(opts.scenarios);nCases=nSc*opts.nReplicates;
assert(nSc>=1 && nCases<=20000,'ASCT:M6:Runs','Invalid or excessive number of cases');
records=cell(nCases,1);truthRecords=cell(nCases,1);k=0;
for s=1:nSc
    base=opts.scenarios(s);
    assert(base.nSources>=3 && base.nSources<=10,'ASCT:M6:Sources', ...
        'M6 scenarios are restricted to 3..10 sources');
    for r=1:opts.nReplicates
        cfg=base;
        cfg.simSeed=mod(double(opts.seed)+r*1009,2147483646)+1; % paired across scenarios
        cfg.evokedAmplitude=0;
        cfg.varianceDrift=0;
        sim=asct_m6_generate(cfg,opts.simulation);
        [roi,inv]=asct_m7_inverse_proxy(sim,opts.inverse);
        oracleFit=asct_m8_fit(sim.observedSources,opts.mvar);
        proxyFit=asct_m8_fit(roi,opts.mvar);
        freq=linspace(1,min(40,sim.fs/2),40);
        oracle=asct_m9_evaluate(oracleFit,sim.trueA,sim.truth,sim.fs,freq);
        proxy=asct_m9_evaluate(proxyFit,sim.trueA,sim.truth,sim.fs,freq);
        k=k+1;
        records{k}=table(s,r,cfg.simSeed,cfg.nSources,cfg.distanceCm, ...
            cfg.nInteractions,cfg.strength,cfg.lag,cfg.snrDb, ...
            oracle.f1,proxy.f1,proxy.f1-oracle.f1,oracle.falsePositiveRate,proxy.falsePositiveRate, ...
            proxy.precision,proxy.recall,proxy.lagMAE,proxy.strengthMAE, ...
            proxy.spectralRadius,proxy.stable,proxy.validForInference,inv.sourceRMSE,inv.spatialLeakageFro, ...
            'VariableNames',{'scenario','replicate','simSeed','nSources','distanceCm', ...
            'nInteractions','strength','lag','snrDb','oracleF1','inverseF1','inverseMinusOracleF1', ...
            'oracleFPR','inverseFPR','inversePrecision','inverseRecall','lagMAE', ...
            'strengthMAE','spectralRadius','stable','validForInference','sourceRMSE','spatialLeakageFro'});
        truthRecords{k}=struct('scenario',s,'replicate',r,'seed',cfg.simSeed, ...
            'trueA',sim.trueA,'truth',sim.truth,'positionsCm',sim.positionsCm, ...
            'sensorPositionsCm',sim.sensorPositionsCm,'mixing',sim.mixing);
    end
end
T=vertcat(records{:});
summary=asct_m9_table_summary(T,{'scenario','nSources','distanceCm', ...
    'nInteractions','strength','lag','snrDb'}, ...
    {'oracleF1','inverseF1','inverseMinusOracleF1', ...
    'inverseFPR','lagMAE','strengthMAE','sourceRMSE'}, ...
    opts.nBootstrap,opts.seed);
assert(~isfolder(outputDir),'ASCT:M6:OutputExists', ...
    'Use a fresh outputDir: %s',outputDir);
mkdir(outputDir);
writetable(T,fullfile(outputDir,'m6_cases.csv'));
writetable(summary,fullfile(outputDir,'m6_summary.csv'));
save(fullfile(outputDir,'m6_results.mat'),'T','summary','truthRecords','opts');
end
