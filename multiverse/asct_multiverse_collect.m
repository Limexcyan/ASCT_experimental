function report = asct_multiverse_collect(multiverseFolder)
%ASCT_MULTIVERSE_COLLECT Read execution status and dependency provenance.
% No statistics or scientific validation: this is an operational report.
assert(ischar(multiverseFolder) || (isstring(multiverseFolder) && isscalar(multiverseFolder)), ...
    'ASCT:Multiverse:InvalidFolder','Folder must be a text scalar');
root=char(multiverseFolder);
checkpoint=fullfile(root,'realdata_results.mat');
assert(isfile(checkpoint),'ASCT:Multiverse:MissingResults', ...
    'Cannot find %s',checkpoint);
s=load(checkpoint,'results','specs','planSnapshot');
assert(isfield(s,'results'),'ASCT:Multiverse:MissingResults', ...
    'No results in %s',checkpoint);
report=struct();
report.folder=root;
report.results=s.results;
report.manifest=readtable(fullfile(root,'realdata_manifest.csv'), ...
    'FileType','text','Delimiter',',','ReadVariableNames',true, ...
    'VariableNamingRule','preserve','TextType','string');
report.counts=struct('total',numel(s.results), ...
    'passed',sum(strcmp({s.results.status},'passed')), ...
    'failed',sum(strcmp({s.results.status},'failed')), ...
    'incomplete',sum(~strcmp({s.results.status},'passed') & ...
        ~strcmp({s.results.status},'failed')));
report.reusedCount=sum(~cellfun(@isempty,{s.results.reuseFrom}));
if isfield(s,'planSnapshot'), report.plan=s.planSnapshot.plan; end
end
