function values = asct_multiverse_metric_truth(runsetup,~,ctx)
%ASCT_MULTIVERSE_METRIC_TRUTH Directed-edge recovery for simulations.
% Requires an explicitly supplied truthConnectivity(target,source) matrix
% aligned with con.chanSel. Never infer ground truth from EEG recordings.
assert(isfield(runsetup,'truthConnectivity') && ...
    ~isempty(runsetup.truthConnectivity), ...
    'ASCT:Metrics:MissingTruth', ...
    'Save an ROI-aligned truthConnectivity matrix in runsetup to use this plugin');
assert(isfield(runsetup,'con') && isfield(runsetup.con,'conName'), ...
    'ASCT:Metrics:MissingConName','Missing con.conName in runsetup');
e=asct_multiverse_evaluate_output(ctx.analysisFolder, ...
    runsetup.con.conName,runsetup.truthConnectivity);
values=struct('meanF1',e.meanF1, ...
    'meanPrecision',e.meanPrecision, ...
    'meanRecall',e.meanRecall, ...
    'meanFalsePositiveRate',mean([e.files.falsePositiveRate]), ...
    'evaluatedFiles',numel(e.files));
end
